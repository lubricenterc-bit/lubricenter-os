import json,re
T=json.load(open('tables.json')); O=json.load(open('objs.json')); F=json.load(open('funcs.json'))
def q(i): return '"'+i.replace('"','""')+'"'
def qn(s,t): return f'{q(s)}.{q(t)}'
PRIV={'a':'INSERT','r':'SELECT','w':'UPDATE','d':'DELETE','D':'TRUNCATE','x':'REFERENCES','t':'TRIGGER','m':'MAINTAIN','X':'EXECUTE','U':'USAGE','C':'CREATE'}
def acl_entries(acl):
    if not acl: return []
    acl=acl.strip('{}')
    out=[]
    for e in re.findall(r'(?:"[^"]*"|[^,])+',acl):
        e=e.strip('"')
        g,rest=e.split('=',1); privs=rest.split('/')[0]
        g=g or 'PUBLIC'
        ps=[PRIV[c] for c in privs if c in PRIV]
        out.append((g,ps))
    return out
ROLES=['PUBLIC','anon','authenticated','service_role']
def grants(objtype,name,acl,cols=None):
    s=[f'REVOKE ALL ON {objtype} {name} FROM {", ".join(ROLES)};']
    for g,ps in acl_entries(acl):
        if g in ('postgres','supabase_admin'): continue
        if ps: s.append(f'GRANT {", ".join(ps)} ON {objtype} {name} TO {g if g=="PUBLIC" else q(g)};')
    return s
P={k:[] for k in ['pre','seq','tab','fn','view','def','seqown','con_pu','con_c','con_f','idx','trg','rls','pol','acl']}
P['pre']+=['CREATE SCHEMA IF NOT EXISTS lubricenter_private;']
for x in O:
    if x['k']=='nsp' and x['s']=='lubricenter_private':
        P['pre'].append('REVOKE ALL ON SCHEMA lubricenter_private FROM PUBLIC, anon, authenticated, service_role;')
        for g,ps in acl_entries(x['d']):
            if g!='postgres' and ps: P['pre'].append(f'GRANT {", ".join(ps)} ON SCHEMA lubricenter_private TO {q(g)};')
    if x['k']=='seq':
        j=json.loads(x['d']); n=qn(x['s'],x['t'])
        P['seq'].append(f"CREATE SEQUENCE IF NOT EXISTS {n} AS {j['ty']} INCREMENT {j['inc']} MINVALUE {j['min']} MAXVALUE {j['max']} START {j['start']} CACHE {j['cache']}{' CYCLE' if j['cycle'] else ''};")
        if j.get('owned'): P['seqown'].append(f"ALTER SEQUENCE {n} OWNED BY {qn(x['s'],j['owned']['t'])}.{q(j['owned']['c'])};")
        P['acl']+=grants('SEQUENCE',n,j['acl'])
for t in T:
    n=qn(t['s'],t['t']); cols=[]
    for c in t['cols']:
        d=f"{q(c['n'])} {c['ty']}"
        if c['coll']: d+=f' COLLATE {q(c["coll"])}'
        if c['gen']=='s': d+=f" GENERATED ALWAYS AS ({c['def']}) STORED"
        if c['id']=='a': d+=' GENERATED ALWAYS AS IDENTITY'
        if c['id']=='d': d+=' GENERATED BY DEFAULT AS IDENTITY'
        if c['nn']: d+=' NOT NULL'
        cols.append(d)
        if c['def'] and c['gen']!='s':
            P['def'].append(f"ALTER TABLE {n} ALTER COLUMN {q(c['n'])} SET DEFAULT {c['def']};")
    P['tab'].append(f"CREATE TABLE IF NOT EXISTS {n} (\n  "+",\n  ".join(cols)+"\n);")
    if t['rls']: P['rls'].append(f'ALTER TABLE {n} ENABLE ROW LEVEL SECURITY;')
    if t['frls']: P['rls'].append(f'ALTER TABLE {n} FORCE ROW LEVEL SECURITY;')
    P['acl']+=grants('TABLE',n,t['acl'])
    for ca in (t['colacl'] or []):
        for g,ps in acl_entries(ca['acl']):
            if g in('postgres',) or not ps: continue
            P['acl'].append(f"GRANT {', '.join(p+' ('+q(ca['n'])+')' for p in ps)} ON TABLE {n} TO {g if g=='PUBLIC' else q(g)};")
for f in F:
    P['fn'].append(f['d'].rstrip()+';' if not f['d'].rstrip().endswith(';') else f['d'])
    # Sin permisos explícitos (NULL) = ejecución pública por defecto en Postgres
    P['acl']+=grants('FUNCTION',f"{qn(f['s'],f['nm'])}({f['args']})",f['acl'] or '{=X/postgres,postgres=X/postgres}')
for x in O:
    n=qn(x['s'],x['t'])
    if x['k']=='view':
        opts=f" WITH ({x['nm']})" if x['nm'] else ''
        P['view'].append(f"CREATE OR REPLACE VIEW {qn(x['s'],x['t'])}{opts} AS\n{x['d']}")
        P['acl']+=grants('TABLE',n,x['ty'])
    elif x['k']=='con':
        st=f"ALTER TABLE {n} ADD CONSTRAINT {q(x['nm'])} {x['d']};"
        if x['ty'] in('p','u'): P['con_pu'].append(st)
        elif x['ty']=='f': P['con_f'].append(st)
        elif x['ty']=='n': pass
        else: P['con_c'].append(st)
    elif x['k']=='idx': P['idx'].append(x['d']+';')
    elif x['k']=='trg':
        P['trg'].append(x['d']+';')
        if x['ty']=='D': P['trg'].append(f"ALTER TABLE {n} DISABLE TRIGGER {q(x['nm'])};")
    elif x['k']=='pol':
        j=json.loads(x['d'])
        roles=j['roles']; roles=roles if isinstance(roles,list) else roles.strip('{}').split(',')
        s=f"CREATE POLICY {q(x['nm'])} ON {n} AS {x['ty']} FOR {j['cmd']} TO {', '.join(r if r=='public' else q(r) for r in roles)}"
        if j['qual']: s+=f" USING ({j['qual']})"
        if j['with_check']: s+=f" WITH CHECK ({j['with_check']})"
        P['pol'].append(s+';')
order=['pre','seq','tab','fn','view','def','seqown','con_pu','con_c','con_f','idx','trg','rls','pol','acl']
stmts=[{'p':i,'ph':k,'sql':s} for i,k in enumerate(order) for s in P[k]]
json.dump(stmts,open('norte_schema.json','w'))
for k in order: print(k,len(P[k]))
print(len(stmts), sum(len(s['sql']) for s in stmts))
